import { NextResponse } from "next/server";
import { getServerSession } from "next-auth";
import { authOptions } from "@/lib/auth";
import { resend, EMAIL_FROM } from "@/lib/email";
import { buildExportAttachment } from "@/lib/export-attachment";
import type { ExportFormat, ExportHeader } from "@/lib/export-attachment";

export const runtime = "nodejs";

const ALLOWED_FORMATS: ExportFormat[] = ["csv", "xlsx", "pdf"];

export async function POST(req: Request) {
  const session = await getServerSession(authOptions);
  if (!session?.user?.email) {
    return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
  }

  // Always deliver to the session user's own email — ignores any client-supplied
  // recipients to prevent open-relay abuse.
  const to = session.user.email;

  let body: {
    data?: unknown;
    headers?: unknown;
    format?: unknown;
    subject?: unknown;
    message?: unknown;
    filename?: unknown;
    // recipients and user are intentionally ignored
  };

  try {
    body = await req.json();
  } catch {
    return NextResponse.json({ error: "Invalid JSON body" }, { status: 400 });
  }

  const { data, headers, format, subject, message, filename } = body;

  // Validate format
  if (!format || !ALLOWED_FORMATS.includes(format as ExportFormat)) {
    return NextResponse.json(
      { error: `format must be one of: ${ALLOWED_FORMATS.join(", ")}` },
      { status: 400 }
    );
  }

  // Validate data
  if (!Array.isArray(data) || data.length === 0) {
    return NextResponse.json({ error: "data must be a non-empty array" }, { status: 400 });
  }

  // Validate headers
  if (!Array.isArray(headers) || headers.length === 0) {
    return NextResponse.json({ error: "headers must be a non-empty array" }, { status: 400 });
  }

  const exportFormat = format as ExportFormat;
  const exportHeaders = headers as ExportHeader[];
  const exportData = data as Record<string, unknown>[];

  const baseFilename =
    typeof filename === "string" && filename.trim()
      ? filename.trim()
      : `export_${new Date().toISOString().split("T")[0]}`;

  const emailSubject =
    typeof subject === "string" && subject.trim()
      ? subject.trim()
      : `Your data export – ${new Date().toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric" })}`;

  const emailMessage =
    typeof message === "string" && message.trim()
      ? message.trim()
      : "Please find your requested data export attached.";

  let attachment: Awaited<ReturnType<typeof buildExportAttachment>>;
  try {
    attachment = await buildExportAttachment(exportFormat, exportData, exportHeaders, baseFilename);
  } catch (err) {
    const msg = err instanceof Error ? err.message : "Failed to build attachment";
    return NextResponse.json({ error: msg }, { status: 500 });
  }

  const html = `<div style="font-family:Arial,Helvetica,sans-serif;font-size:15px;line-height:1.6;color:#1e293b;max-width:640px;margin:0 auto">
<p>${emailMessage.replace(/\n/g, "<br>")}</p>
<hr style="border:none;border-top:1px solid #e2e8f0;margin:24px 0" />
<p style="font-size:12px;color:#94a3b8">This export was generated by Kazi and sent to your registered email address.</p>
</div>`;

  const { data: resendData, error } = await resend.emails.send({
    from: EMAIL_FROM,
    to,
    subject: emailSubject,
    html,
    text: emailMessage,
    attachments: [
      {
        content: attachment.content,
        filename: attachment.filename,
      },
    ],
  });

  if (error) {
    return NextResponse.json({ error: error.message }, { status: 500 });
  }

  return NextResponse.json({ id: resendData?.id });
}
